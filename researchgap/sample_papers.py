def build_sample_papers() -> list[tuple[str, bytes]]:
    """Returns [(filename, pdf_bytes)] for papers A, B, C."""
    return [
        (PAPERS["A"]["filename"], _paper_a()),
        (PAPERS["B"]["filename"], _paper_b()),
        (PAPERS["C"]["filename"], _paper_c()),
    ]


